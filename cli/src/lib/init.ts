import { mkdirSync, writeFileSync, existsSync } from 'fs'
import { join, resolve } from 'path'
import { colors, symbols, header } from './ui.js'

const PACKAGE_JSON = (name: string) => JSON.stringify({
  name: name,
  version: '0.1.0',
  description: `MCP server: ${name}`,
  type: 'module',
  bin: { [name]: './dist/index.js' },
  scripts: {
    build: 'tsup',
    dev: 'tsup --watch',
  },
  keywords: ['mcp', 'model-context-protocol', 'ai', 'tools'],
  license: 'MIT',
  dependencies: {
    '@modelcontextprotocol/sdk': '^1.0.0',
  },
  devDependencies: {
    '@types/node': '^22.0.0',
    tsup: '^8.3.0',
    typescript: '^5.6.0',
  },
}, null, 2) + '\n'

const TSCONFIG = JSON.stringify({
  compilerOptions: {
    target: 'ES2022',
    module: 'ESNext',
    moduleResolution: 'bundler',
    lib: ['ES2022'],
    outDir: './dist',
    rootDir: './src',
    strict: true,
    esModuleInterop: true,
    skipLibCheck: true,
    resolveJsonModule: true,
  },
  include: ['src/**/*'],
}, null, 2) + '\n'

const TSUP_CONFIG = `import { defineConfig } from 'tsup'

export default defineConfig({
  entry: ['src/index.ts'],
  format: ['esm'],
  target: 'node18',
  outDir: 'dist',
  clean: true,
  dts: true,
  banner: { js: '#!/usr/bin/env node' },
})
`

const SERVER_TEMPLATE = (name: string) => `#!/usr/bin/env node
import { Server } from '@modelcontextprotocol/sdk/server/index.js'
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js'
import {
  CallToolRequestSchema,
  ListToolsRequestSchema,
} from '@modelcontextprotocol/sdk/types.js'

const server = new Server(
  { name: '${name}', version: '0.1.0' },
  { capabilities: { tools: {} } }
)

// ─── Define your tools here ───────────────────────────────
server.setRequestHandler(ListToolsRequestSchema, async () => {
  return {
    tools: [
      {
        name: 'hello',
        description: 'A sample tool that returns a greeting',
        inputSchema: {
          type: 'object',
          properties: {
            name: { type: 'string', description: 'Name to greet' },
          },
          required: ['name'],
        },
      },
    ],
  }
})

// ─── Handle tool calls ────────────────────────────────────
server.setRequestHandler(CallToolRequestSchema, async (request) => {
  const { name, arguments: args } = request.params

  switch (name) {
    case 'hello': {
      const who = (args as any)?.name || 'world'
      return {
        content: [{ type: 'text', text: \`Hello, \${who}! from ${name}\` }],
      }
    }
    default:
      return { content: [{ type: 'text', text: \`Unknown tool: \${name}\` }] }
  }
})

// ─── Start the server ─────────────────────────────────────
async function main() {
  const transport = new StdioServerTransport()
  await server.connect(transport)
  console.error('${name} MCP server running on stdio')
}

main().catch((err) => {
  console.error('Fatal error:', err)
  process.exit(1)
})
`

