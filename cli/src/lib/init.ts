const GITIGNORE = `node_modules/
dist/
*.tsbuildinfo
.env
.DS_Store
`

export function initServer(name: string, options: { path?: string }): void {
  console.log(header(`Scaffolding ${name}`))

  const basePath = options.path ? resolve(options.path) : process.cwd()
  const serverPath = join(basePath, name)

  if (existsSync(serverPath)) {
    console.log(`  ${symbols.cross} Directory already exists: ${colors.red(serverPath)}\n`)
    return
  }

  // Create directory structure
  mkdirSync(join(serverPath, 'src'), { recursive: true })

  // Write files
  writeFileSync(join(serverPath, 'package.json'), PACKAGE_JSON(name))
  writeFileSync(join(serverPath, 'tsconfig.json'), TSCONFIG)
  writeFileSync(join(serverPath, 'tsup.config.ts'), TSUP_CONFIG)
  writeFileSync(join(serverPath, 'src', 'index.ts'), SERVER_TEMPLATE(name))
  writeFileSync(join(serverPath, 'README.md'), README(name))
  writeFileSync(join(serverPath, '.gitignore'), GITIGNORE)

  console.log(`  ${symbols.check} Created ${colors.bold(name)} at:`)
  console.log(`  ${colors.gray(serverPath)}\n`)
  console.log(`  ${colors.bold('Next steps:')}`)
  console.log(`    ${colors.gray('cd')} ${name}`)
  console.log(`    ${colors.gray('npm install')}`)
  console.log(`    ${colors.gray('npm run build')}`)
  console.log(`    ${colors.gray('node dist/index.js')}  ${colors.gray('# test it')}`)
  console.log(`\n  ${colors.gray('Then add to your AI client config and test with Claude/Cursor.')}`)
  console.log(`  ${colors.gray('When ready, submit to MCP Hub:')}`)
  console.log(`  ${colors.gray('https://github.com/e2sy/mcp-hub/blob/main/CONTRIBUTING.md')}\n`)
}
